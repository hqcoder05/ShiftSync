const currentColors = new Set(Object.values(colors).map(value => value.toUpperCase()));
function mappedHex(hex) {
  let result = hex.toUpperCase();
  const seen = new Set();
  while (!currentColors.has(result) && legacyColorMap[result] && !seen.has(result)) {
    seen.add(result);
    result = legacyColorMap[result].toUpperCase();
  }
  return result;
}

// Also supports legacy inline icon/gradient values and translucent role colors.
// Unrecognized strings, named colors and non-color values pass through intact.
export function resolveUiColor(value) {
  if (typeof value !== 'string') return value;

  const hex = value.match(/^#([\da-f]{3}|[\da-f]{6}|[\da-f]{8})$/i);
  if (hex) {
    const digits = hex[1];
    const base = digits.length === 3
      ? `#${digits.split('').map((digit) => digit + digit).join('')}`
      : `#${digits.slice(0, 6)}`;
    const mapped = mappedHex(base);
    // Preserve the source spelling and alpha when the base needs no migration.
    if (mapped === base.toUpperCase()) return value;
    return digits.length === 8 ? `${mapped}${digits.slice(6)}` : mapped;
  }

  const rgb = value.match(/^(rgb|rgba)\(\s*(\d{1,3})\s*,\s*(\d{1,3})\s*,\s*(\d{1,3})\s*(?:,\s*(0|1|0?\.\d+|1\.0+)\s*)?\)$/i);
  if (!rgb) return value;
  const sourceChannels = rgb.slice(2, 5).map(Number);
  if (sourceChannels.some((channel) => channel > 255)) return value;
  if ((rgb[1].toLowerCase() === 'rgba') !== (rgb[5] !== undefined)) return value;
  const base = `#${sourceChannels.map((channel) => channel.toString(16).padStart(2, '0')).join('')}`;
  const mapped = mappedHex(base);
  if (mapped === base.toUpperCase()) return value;
  const channels = mapped.slice(1).match(/../g).map((channel) => parseInt(channel, 16));
  return rgb[5] === undefined
    ? `rgb(${channels.join(', ')})`
    : `rgba(${channels.join(', ')}, ${rgb[5]})`;
}
