const fs = require('fs');
const path = require('path');
const { chromium } = require('playwright');

// Run from the mobile project root. CHROMIUM_PATH is optional when Playwright's
// managed browser is installed. No external services or user data are needed.
(async () => {
  const root = process.cwd();
  const browser = await chromium.launch({
    executablePath: process.env.CHROMIUM_PATH || path.resolve('qa-week2-2026-10-20/browsers/chromium-1248/chrome-win64/chrome.exe'),
    headless: true,
    args: ['--enable-unsafe-swiftshader', '--use-angle=swiftshader'],
  });
  try {
    const page = await browser.newPage();
    await page.route('http://avatars.local/**', async (route) => {
      const requested = new URL(route.request().url()).pathname;
      if (requested === '/') return route.fulfill({ contentType: 'text/html', body: '<!doctype html><title>ShiftSync avatar renderer</title><script type="importmap">{"imports":{"three":"/node_modules/three/build/three.module.js"}}</script>' });
      const file = path.resolve(root, '.' + requested);
      if (!file.startsWith(root + path.sep)) throw new Error('Asset escaped project root');
      return route.fulfill({ contentType: 'text/javascript', body: fs.readFileSync(file) });
    });
    await page.goto('http://avatars.local/');
    const portraits = await page.evaluate(async () => {
      const { renderAvatarPortraits } = await import('/scripts/avatarPortraitScene.js');
      return renderAvatarPortraits();
    });
    const output = path.join(root, 'assets', 'avatars-low-poly');
    if (process.argv.includes('--png')) {
      fs.mkdirSync(output, { recursive: true });
      for (const [framing, choices] of Object.entries(portraits)) for (const [id, uri] of Object.entries(choices))
        fs.writeFileSync(path.join(output, `${id}-${framing}.png`), Buffer.from(uri.split(',')[1], 'base64'));
    }
    const previews = Object.fromEntries(Object.entries(portraits).map(([framing, choices]) => [framing, Object.fromEntries(Object.entries(choices).map(([id, uri]) => [id, { uri }]))]));
    fs.writeFileSync(path.join(root, 'components', 'avatarPortraitData.js'),
      '// Generated by scripts/generate-avatar-portraits.cjs. Bundled previews need no Metro asset lookup.\nexport default ' + JSON.stringify(previews) + ';\n');
    console.log(`Rendered ${Object.keys(portraits.head).length} head and ${Object.keys(portraits.full).length} full-body previews.`);
  } finally {
    await browser.close();
  }
})().catch((error) => { console.error(error); process.exitCode = 1; });
